#!/usr/bin/env python3
"""Write a dummy extracted/ tree for the check_all self-tests and CI (no ROM needed).

    python tests/make_dummy_image.py OUTROOT [--size BYTES] [--seed TEXT]

Writes OUTROOT/extracted/{code.bin,text.bin,rodata.bin,data.bin,layout.json}. The bytes
are a deterministic pseudo-random stream (SHA-256 of seed + counter), so the same
arguments always give the same files. Nothing here comes from the game: it is a
stand-in with the right file names, so rows that need "rom:code" run instead of
SKIPping, and the byte-leak scan (check_all.py hygiene-leak) has something to find.

What it can and cannot do (docs/CHECKS.md):
  * hygiene-leak: yes; plant bytes of the dummy code.bin in a tracked file and the row
    must FAIL; a clean tree must PASS.
  * code-hash, m1-tests, diff-func: no; the dummy is not the retail code.bin (its
    layout.json says "dummy": true), so those gates fail on the hash, as they should.
Refuses to write into a folder named extracted/ of a tree that already has a
non-dummy code.bin.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


def stream(seed: str, n: int) -> bytes:
    out = bytearray()
    i = 0
    s = seed.encode()
    while len(out) < n:
        out += hashlib.sha256(s + i.to_bytes(8, "little")).digest()
        i += 1
    return bytes(out[:n])


def make(root: Path, size: int = 1 << 18, seed: str = "awakening-dummy") -> Path:
    """Write the dummy tree under root/extracted and return that folder."""
    ext = Path(root) / "extracted"
    lay_path = ext / "layout.json"
    if (ext / "code.bin").exists():
        try:
            if not json.loads(lay_path.read_text(encoding="utf-8")).get("dummy"):
                raise SystemExit(f"{ext}: holds a real extracted/ tree; not overwriting it")
        except (OSError, ValueError):
            raise SystemExit(f"{ext}: has a code.bin but no dummy layout.json; not overwriting it")
    size -= size % 0x1000
    if size < 0x3000:
        raise SystemExit("--size must be at least 0x3000")
    code = stream(seed, size)
    t, r = size // 2, size * 3 // 4            # text | rodata | data, page aligned
    t -= t % 0x1000
    r -= r % 0x1000
    parts = {"text": code[:t], "rodata": code[t:r], "data": code[r:]}
    ext.mkdir(parents=True, exist_ok=True)
    (ext / "code.bin").write_bytes(code)
    layout = {"dummy": True, "note": "generated by tests/make_dummy_image.py; not a game dump",
              "product_code": "DUMMY", "seed": seed,
              "code_bin": {"size": len(code), "sha1": hashlib.sha1(code).hexdigest()}}
    off, addr = 0, 0x00100000
    for name, data in parts.items():
        (ext / f"{name}.bin").write_bytes(data)
        layout[name] = {"addr": addr, "size": len(data), "pages": len(data) // 0x1000,
                        "file_offset": off, "sha1": hashlib.sha1(data).hexdigest()}
        off += len(data)
        addr += len(data)
    lay_path.write_text(json.dumps(layout, indent=1) + "\n", encoding="utf-8")
    return ext


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out")
    ap.add_argument("--size", type=lambda s: int(s, 0), default=1 << 18)
    ap.add_argument("--seed", default="awakening-dummy")
    a = ap.parse_args()
    ext = make(Path(a.out), a.size, a.seed)
    print(f"wrote dummy image in {ext}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
