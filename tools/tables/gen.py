#!/usr/bin/env python3
"""Generate the text renderings of the table layouts (layout only, no values).

Standard library only.

    python tools/tables/gen.py structs   write config/tables/structs.h.txt: C++ struct
                                         declarations of every table record (ARM32 view:
                                         relocated pointers are 32-bit pointers), with
                                         static_asserts on every field offset and the size
    python tools/tables/gen.py doc       rewrite the generated part of docs/TABLES.md
                                         (between the <!-- tables:begin/end --> markers)
    python tools/tables/gen.py check     both outputs are up to date, and the struct text
                                         compiles with arm-none-eabi-g++ -fsyntax-only (when
                                         tools/config.local.json names the toolchain)

The structs are named <Layout>Data (tables that share a layout, Person and PersonChapter,
share one struct) and are not included by any build. The text is self-contained (its own
u8..u64 typedefs). Inputs: config/tables/tables.csv and config/tables/*.csv. Record counts
in the doc are read from the user's RomFS when it is present.

    --gxx PATH   g++ for the compile check (default: tools/config.local.json binutils_dir)
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tablelib as T  # noqa: E402

sys.path.insert(0, os.path.join(T.ROOT, "tools"))
from gamecfg import GAME  # noqa: E402

STRUCTS = os.path.join(T.CONFIG, "structs.h.txt")
DOC = os.path.join(T.ROOT, "docs", "TABLES.md")
BEGIN, END = "<!-- tables:begin (generated by tools/tables/gen.py doc) -->", "<!-- tables:end -->"
CTYPE = {(1, False): "u8", (1, True): "s8", (2, False): "u16", (2, True): "s16",
         (4, False): "u32", (4, True): "s32", (8, False): "u64"}


def tables_with_layouts(reg):
    return [n for n in reg if os.path.exists(T.layout_path(n))]


def layouts(reg) -> list[str]:
    """Distinct layout names, in registry order."""
    out = []
    for n in tables_with_layouts(reg):
        if reg[n].layout not in out:
            out.append(reg[n].layout)
    return out


def c_decl(f: T.Field) -> str:
    n = f.name
    if f.kind == "hex":
        return f"u8 {n}[{f.n}];"
    if f.kind == "int":
        base = CTYPE[(f.width, f.signed)]
        return f"{base} {n}[{f.n}];" if f.n > 1 else f"{base} {n};"
    if f.kind == "ref":
        base = CTYPE[(f.width, False)]
        return f"{base} {n}[{f.n}];" if f.n > 1 else f"{base} {n};"
    if f.kind in ("flags", "enum"):
        return f"{CTYPE[(f.width, False)]} {n};"
    if f.kind == "str":
        return f"const char* {n};"
    if f.kind == "lptr":
        return f"const struct {reg_layout(f.ref)}Data* {n};"
    if f.kind == "ptr":
        return f"const void* {n};"
    if f.kind == "pad":
        return f"u8 {n}[{f.size}];"
    raise ValueError(f.kind)


_LAYOUT_OF: dict[str, str] = {}


def reg_layout(table: str) -> str:
    return _LAYOUT_OF.get(table, table)


def gen_structs(reg) -> str:
    _LAYOUT_OF.update({n: t.layout for n, t in reg.items()})
    out = ["// GENERATED by tools/tables/gen.py structs from config/tables/*.csv -- do not edit.",
           f"// Record layouts of the RomFS data tables ({GAME.game}, {GAME.edition}). Layout only: no values.",
           "// ARM32 view: 'const char*' / pointer fields are the container's relocated words.",
           "// Confidence per field in [brackets]; evidence in config/tables/<Layout>.csv.",
           "// Text only: nothing includes this file.",
           "",
           "#include <stddef.h>",
           "typedef unsigned char u8; typedef signed char s8; typedef unsigned short u16; typedef short s16;",
           "typedef unsigned int u32; typedef int s32; typedef unsigned long long u64;",
           ""]
    names = layouts(reg)
    for n in names:
        out.append(f"struct {n}Data;")
    out.append("")
    for n in names:
        users = [k for k in tables_with_layouts(reg) if reg[k].layout == n]
        t = reg[users[0]]
        fields = T.load_layout(users[0])
        for u in users:
            tu = reg[u]
            out.append(f"// {u}: {tu.file}, start {tu.start}, count {tu.count}, record 0x{tu.size:X} bytes. {tu.description}")
        out.append(f"struct {n}Data {{")
        width = max(len(c_decl(f)) for f in fields)
        for f in fields:
            d = c_decl(f)
            extra = f" {f.type}" if f.kind in ("flags", "ref", "lptr", "enum", "hex") or f.type == "str:self" else ""
            el = f" ({', '.join(f.elements)})" if f.elements else ""
            out.append(f"    {d:<{width}}  // +0x{f.offset:03X}{extra}{el} [{f.confidence}]")
        out.append("};")
        out.append(f"static_assert(sizeof({n}Data) == 0x{t.size:X}, \"{n}Data size\");")
        for f in fields:
            out.append(f"static_assert(offsetof({n}Data, {f.name}) == 0x{f.offset:X}, \"{n}Data::{f.name}\");")
        out.append("")
    return "\n".join(out)


def md_escape(s: str) -> str:
    return s.replace("|", "\\|")


def gen_doc_section(reg) -> str:
    lines = [BEGIN, ""]
    names = tables_with_layouts(reg)
    have_romfs = os.path.isdir(T.ROMFS)
    lines.append("| Table | File(s) | Record | Records | Fields (high / medium / low) |")
    lines.append("|---|---|---:|---:|---|")
    counts = {}
    for n in names:
        t = reg[n]
        fields = T.load_layout(n)
        cnt = "?"
        if have_romfs:
            try:
                cnt = 0
                for rel in t.files():
                    cnt += T.locate(t, T.container(rel))[1]
                if "*" in t.file:
                    cnt = f"{cnt} in {len(t.files())} files"
            except (OSError, T.LayoutError, KeyError):
                cnt = "?"
        counts[n] = cnt
        conf = [sum(1 for f in fields if f.confidence == c) for c in ("high", "medium", "low")]
        files = " ".join(f"`{p}`" for p in t.file.split(";"))
        lines.append(f"| [{n}](#{n.lower()}) | {files} | 0x{t.size:X} | {cnt} | {len(fields)} ({conf[0]} / {conf[1]} / {conf[2]}) |")
    lines.append("")
    for n in names:
        t = reg[n]
        fields = T.load_layout(n)
        lines.append(f"### {n}")
        lines.append("")
        lines.append(f"{t.description}. File `{t.file.replace(';', '` `')}`; start `{t.start}`; count `{t.count}`; "
                     f"record size 0x{t.size:X}; {counts[n]} records."
                     + (f" Code: base pointer in `{t.code_global}`" + (f", count in `{t.count_global}`" if t.count_global else "") + "."
                        if t.code_global else ""))
        lines.append("")
        if t.layout != n:
            lines.append(f"Same record layout as [{t.layout}](#{t.layout.lower()}) (config/tables/{t.layout}.csv).")
            lines.append("")
            continue
        lines.append("| Offset | Size | Type | Name | Conf. | Evidence |")
        lines.append("|---|---:|---|---|---|---|")
        for f in fields:
            nm = f.name + (f" ({', '.join(f.elements)})" if f.elements else "")
            lines.append(f"| +0x{f.offset:03X} | {f.size} | `{f.type}` | {md_escape(nm)} | {f.confidence} | {md_escape(f.evidence)} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def write_doc(reg) -> str:
    with open(DOC, encoding="utf-8") as fh:
        doc = fh.read()
    if BEGIN not in doc or END not in doc:
        raise SystemExit("docs/TABLES.md has no generated-section markers")
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + gen_doc_section(reg) + tail


def compile_check(text: str, gxx: str | None = None) -> str:
    if not gxx:
        cfgp = os.path.join(T.ROOT, "tools", "config.local.json")
        try:
            with open(cfgp, encoding="utf-8") as fh:
                d = json.load(fh)["binutils_dir"]
        except (OSError, KeyError, ValueError):
            return "skipped (no tools/config.local.json binutils_dir; pass --gxx)"
        gxx = next((os.path.join(d, n) for n in ("arm-none-eabi-g++.exe", "arm-none-eabi-g++")
                    if os.path.exists(os.path.join(d, n))), None)
    if not gxx:
        return "skipped (arm-none-eabi-g++ not found)"
    with tempfile.TemporaryDirectory() as td:
        src = os.path.join(td, "structs_check.cpp")
        with open(src, "w", encoding="utf-8") as fh:
            fh.write(text + "\n")
        r = subprocess.run([gxx, "-std=gnu++11", "-marm", "-mcpu=mpcore", "-fsyntax-only", src],
                           capture_output=True, text=True)
        if r.returncode:
            raise SystemExit("structs.h.txt does not compile:\n" + r.stderr[-3000:])
    return "compiles with arm-none-eabi-g++ (all offset/size static_asserts hold)"


def main() -> int:
    args = sys.argv[1:]
    gxx = None
    if "--gxx" in args:
        i = args.index("--gxx")
        gxx = args[i + 1]
        del args[i:i + 2]
    cmd = args[0] if args else "check"
    reg = T.registry()
    s = gen_structs(reg) + "\n"
    if cmd == "structs":
        with open(STRUCTS, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(s)
        print(f"wrote {os.path.relpath(STRUCTS, T.ROOT)}; {compile_check(s, gxx)}")
        return 0
    if cmd == "doc":
        d = write_doc(reg)
        with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(d)
        print(f"updated {os.path.relpath(DOC, T.ROOT)}")
        return 0
    if cmd == "check":
        bad = 0
        with open(STRUCTS, encoding="utf-8") as fh:
            if fh.read() != s:
                print("config/tables/structs.h.txt is out of date (run gen.py structs)")
                bad = 1
        with open(DOC, encoding="utf-8") as fh:
            if fh.read() != write_doc(reg):
                print("docs/TABLES.md generated section is out of date (run gen.py doc)")
                bad = 1
        print(f"structs: {compile_check(s, gxx)}")
        print("generated files up to date" if not bad else "generated files OUT OF DATE")
        return bad
    raise SystemExit(__doc__)


if __name__ == "__main__":
    sys.exit(main())
