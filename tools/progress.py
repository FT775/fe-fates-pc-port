#!/usr/bin/env python3
"""Progress table from config/functions.csv (and config/status.csv once matching starts).

    python tools/progress.py            print the table
    python tools/progress.py --readme   also rewrite the block between the
                                        <!-- progress --> markers in README.md

Only game code counts toward matching progress; library code (SDK, NintendoWare, NEX,
Pia, MoLive, Live2D, pead, zlib, C/C++ runtime) is parked as asm and reported separately.
For Fates the registry comes from the shipped symbol map (tools/fates/symbols.py), so
"Named" counts functions with a map or hand name; only funcmap-only starts stay
func_XXXXXXXX. Library tags are listed in docs/SYMBOLS.md.
Status per function: asm (default) | matched | nonmatching, from config/status.csv
(columns addr,status) when it exists.
"""
from __future__ import annotations

import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAME = {"game", "unknown"}   # unknown counted with game until tagged, and shown separately


def main() -> int:
    funcs = list(csv.DictReader((ROOT / "config" / "functions.csv").open(encoding="utf-8")))
    # status comes from config/src_map.csv (matched | nonmatching | asm), the pipeline's
    # source of truth (docs/MATCHING.md); rows matched only with the GCC stand-in are
    # counted separately, since they still need confirming with armcc.
    status = {}
    sp = ROOT / "config" / "src_map.csv"
    if sp.is_file():
        for r in csv.DictReader(sp.open(encoding="utf-8")):
            st = r["status"].strip()
            if st == "matched" and "standin" in (r.get("compiler") or ""):
                st = "matched_standin"
            status[int(r["addr"], 16)] = st
    agg = defaultdict(lambda: defaultdict(int))
    for r in funcs:
        a, e = int(r["addr"], 16), int(r["end"], 16)
        lib = r["library"] or "unknown"
        st = status.get(a, "asm")
        g = agg[lib]
        g["funcs"] += 1
        g["bytes"] += e - a
        g["named"] += not r["name"].startswith("func_")
        g[f"{st}_funcs"] += 1
        g[f"{st}_bytes"] += e - a
    total_b = sum(g["bytes"] for g in agg.values())
    game_b = sum(agg[l]["bytes"] for l in agg if l in GAME)
    game_f = sum(agg[l]["funcs"] for l in agg if l in GAME)
    matched_b = sum(agg[l]["matched_bytes"] for l in agg if l in GAME)
    matched_f = sum(agg[l]["matched_funcs"] for l in agg if l in GAME)
    named = sum(g["named"] for g in agg.values())

    lines = ["| Library | Functions | Bytes | % of .text | Named | Matched (armcc) | Matched (GCC stand-in) |",
             "|---|---:|---:|---:|---:|---:|---:|"]
    for lib in sorted(agg, key=lambda l: -agg[l]["bytes"]):
        g = agg[lib]
        lines.append(f"| {lib} | {g['funcs']:,} | {g['bytes']:,} | {100 * g['bytes'] / total_b:.1f}% | "
                     f"{g['named']:,} | {g['matched_funcs']:,} | {g['matched_standin_funcs']:,} |")
    standin = sum(g["matched_standin_funcs"] for g in agg.values())
    lines.append(f"| **total** | {len(funcs):,} | {total_b:,} | 100% | {named:,} | {matched_f:,} | {standin:,} |")
    summary = (f"**Matching progress (game + untagged code): {matched_f:,} / {game_f:,} functions, "
               f"{matched_b:,} / {game_b:,} bytes ({100 * matched_b / max(1, game_b):.2f}%).** "
               f"Named functions: {named:,} / {len(funcs):,}.")
    text = summary + "\n\n" + "\n".join(lines)
    print(text)
    if "--readme" in sys.argv:
        rp = ROOT / "README.md"
        r = rp.read_text(encoding="utf-8")
        block = f"<!-- progress -->\n{text}\n\n_Generated by `python tools/progress.py --readme`._\n<!-- /progress -->"
        if "<!-- progress -->" in r:
            r = re.sub(r"<!-- progress -->.*?<!-- /progress -->", lambda _: block, r, flags=re.S)
        else:
            r = r.rstrip() + "\n\n## Progress\n\n" + block + "\n"
        rp.write_text(r, encoding="utf-8", newline="\n")   # LF on Windows too (.gitattributes)
    return 0


if __name__ == "__main__":
    sys.exit(main())
