/* What replay.c and fakelib need from a 3dsrecomp library beyond the stand-in
   overrides.h (tools/readable/stub/): the exported entry table.

   Written by this project from 3dsrecomp's documentation (docs/interface.md,
   "Loading": a library exports recomp_abi, recomp_entry_count and
   recomp_entries, an array of {address, code} sorted by address, bit 0 of the
   address set for Thumb). No 3dsrecomp code is copied here; 3dsrecomp has no
   licence. tools/harness/abi_check.c compares this layout and the stand-in's
   Context and Host with the generated recomp.h (read in place under build/)
   before replay.exe may load a library (docs/HARNESS.md 3.4). */

#ifndef FE_REPLAY_ABI_H
#define FE_REPLAY_ABI_H

#include <stdint.h>

#define FE_REPLAY_RECOMP_ABI 5u /* the only recomp_abi replay.exe accepts */

typedef struct FeRpEntry { /* = 3dsrecomp's Entry */
    uint32_t address;
    Code code;
} FeRpEntry;

/* one readable override compiled natively into replay.exe (the table is
   generated by tools/harness/harness.py from the sources, or written by hand
   for fakelib) */
typedef struct FeReplayOverride {
    uint32_t address;
    Code code; /* override_0x........ */
    const char *name;
} FeReplayOverride;

extern const FeReplayOverride fe_replay_overrides[];
extern const unsigned fe_replay_override_count;

#endif /* FE_REPLAY_ABI_H */
