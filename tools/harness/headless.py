def load_routes(path: str = ROUTES) -> dict:
    with open(path, encoding="utf-8") as fh:
        routes = json.load(fh)["routes"]
    for name, r in routes.items():
        for key in ("frames", "input", "save_at", "shots"):
            if key not in r:
                raise Stop(f"routes.json: route {name} has no '{key}'")
        if not (0 < int(r["save_at"]) < int(r["frames"])):
            raise Stop(f"routes.json: route {name}: save_at must be inside the run")
        last = -1
        for item in r["input"].split(","):
            if not re.fullmatch(r"\d+:[A-Z+@0-9x]+", item.strip()):
                raise Stop(f"routes.json: route {name}: bad input entry '{item}'")
            at = int(item.strip().split(":")[0])
            if at <= last:
                raise Stop(f"routes.json: route {name}: input '{item}' is not after the one before it")
            if at >= int(r["frames"]):
                raise Stop(f"routes.json: route {name}: input '{item}' is not inside the run")
            last = at
        if "save" in r and not re.fullmatch(r"[A-Za-z0-9_.-]+", str(r["save"])):
            raise Stop(f"routes.json: route {name}: save must be the bare name of a zip in build/harness/saves/")
        for shot in r["shots"]:
            if not (0 < int(shot) < int(r["frames"])):
                raise Stop(f"routes.json: route {name}: shot {shot} is not inside the run")
    bad = _cheats().check_routes(routes)  # the cheat track's rules (docs/CHEATS.md)
    bad += _options_track().check_routes(routes)  # the options track's rules (docs/OPTIONS_WIRING.md section 7)
    if bad:
        raise Stop("routes.json: " + "; ".join(bad))
    return routes


