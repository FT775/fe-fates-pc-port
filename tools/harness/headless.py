# ------------------------------------------------------------------ savestates
_FF_RUN = re.compile(bytes([0xFF]) + b"*")  # a run of 255 bytes (LZ4 length extension)


def lz4_block(src: bytes, size: int) -> bytes:
    """Decodes one LZ4 block (the format lz4_flex::compress_prepend_size writes after its size word).
    Speed (ROBOT.md 5): a run of 255 length bytes is skipped with one regex match, and an overlapping
    match (offset < length, e.g. a run of zero bytes) is written as its period repeated, not piece by
    piece; the bytes are the same."""
    out = bytearray()
    i, n, o = 0, len(src), 0  # o: len(out), kept by hand (len() was a tenth of the time)
    ff = _FF_RUN.match
    while i < n:
        tok = src[i]
        i += 1
        lit = tok >> 4
        if lit == 15:
            j = ff(src, i).end()
            if j >= n:
                raise IndexError("lz4: length cut short")
            lit += 255 * (j - i) + src[j]
            i = j + 1
        if lit:
            out += src[i:i + lit]
            i += lit
            o += lit
        if i >= n:
            break
        off = src[i] | src[i + 1] << 8
        i += 2
        if off == 0 or off > o:
            raise ValueError("lz4: bad match offset")
        ml = tok & 15
        if ml == 15:
            j = ff(src, i).end()
            if j >= n:
                raise IndexError("lz4: length cut short")
            ml += 255 * (j - i) + src[j]
            i = j + 1
        ml += 4
        start = o - off
        o += ml
        if off >= ml:
            out += out[start:start + ml]
        elif off == 1:
            out += bytes((out[start],)) * ml
        else:
            period = out[start:start + off]
            reps, rest = divmod(ml, off)
            out += period * reps
            out += period[:rest]
    if len(out) != size:  # o can run ahead of out only on a cut-short literal, caught here
        raise ValueError(f"lz4: {len(out)} bytes decoded, {size} expected")
    return bytes(out)


def state_sections(data: bytes) -> tuple[str, list[bytes]]:
    """Splits a Zakuro savestate (zakuro-core state/mod.rs: ZAKUROST, version, program id, then
    LZ4 sections: metadata, FCRAM, VRAM, DSP RAM, AXI WRAM) into its decoded sections."""
    if data[:8] != b"ZAKUROST":
        raise ValueError("not a Zakuro savestate")
    vl = struct.unpack_from("<I", data, 8)[0]
    version = data[12:12 + vl].decode("ascii", "replace")
    p = 12 + vl + 8
    out = []
    while p < len(data):
        cl = struct.unpack_from("<Q", data, p)[0]
        p += 8
        comp = data[p:p + cl]
        if len(comp) != cl or cl < 4:
            raise ValueError("savestate cut short")
        p += cl
        out.append(lz4_block(comp[4:], struct.unpack_from("<I", comp, 0)[0]))
    return version, out


def strip_string(meta: bytes, needle: bytes) -> bytes:
    """Replaces needle by <RUN>, with the postcard length (a LEB128 varint) of the string holding it,
    when the string starts with it: a longer run name makes that length byte differ too."""
    out, at = bytearray(), 0
    while True:
        p = meta.find(needle, at)
        if p < 0:
            out += meta[at:]
            return bytes(out)
        q = p
        if q > at and meta[q - 1] < 0x80:
            q -= 1
            while q > at and p - q < 5 and meta[q - 1] >= 0x80:
                q -= 1
        out += meta[at:q] + b"<RUN>"
        at = p + len(needle)


def strip_meta(meta: bytes, own_names: list[str]) -> bytes:
    """The metadata section without the run's own folder names (they differ between runs by design)."""
    for name in own_names:
        for form in {name, name.replace("/", "\\"), name.replace("\\", "/")}:
            meta = strip_string(meta, form.encode("utf-8"))
    return meta


def state_digest(data: bytes, own_names: list[str]) -> dict:
    return sections_digest(*state_sections(data), own_names)


def sections_digest(version: str, secs: list[bytes], own_names: list[str]) -> dict:
    """state_digest on sections already decoded (run() decodes a state once for the digest and keep_meta)."""
    if len(secs) != len(SECTIONS):
        raise ValueError(f"{len(secs)} sections, {len(SECTIONS)} expected")
    meta = strip_meta(secs[0], own_names)
    return {"zakuro": version,
            "sections": {n: hashlib.sha256(s).hexdigest() for n, s in zip(SECTIONS, secs)},
            "meta_bytes": len(secs[0]),
            "meta_stripped": hashlib.sha256(meta).hexdigest(),
            "meta_multiset": hashlib.sha256(bytes(sorted(meta))).hexdigest(),
            "memory": hashlib.sha256(b"".join(hashlib.sha256(s).digest() for s in secs[1:])).hexdigest()}


META_BLOCK = 2  # smallest reordered piece accepted (H4a: two hash maps, entries of 4 and of 2 bytes)


def compare_meta(a: bytes, b: bytes) -> tuple[bool, str]:
    """Two stripped metadata sections: (only reordered, verdict). Equal byte counts are not enough:
    outside the span between the common prefix and suffix the bytes are equal by construction, and
    inside it every byte of each side must lie in a META_BLOCK-byte piece that also occurs inside
    the other side's span (so a value whose own bytes are reversed, e.g. 10203040 vs 40302010, is
    DIFFERENT). Evidence of reordered blocks, not a proof of a hash-map permutation."""
    if a == b:
        return True, "identical"
    if len(a) != len(b) or sorted(a) != sorted(b):
        return False, "DIFFERENT"
    n, p = len(a), 0
    while p < n and a[p] == b[p]:
        p += 1
    s = 0
    while s < n - p and a[n - 1 - s] == b[n - 1 - s]:
        s += 1
    sa, sb = a[p:n - s], b[p:n - s]
    if len(sa) < META_BLOCK:
        return False, "DIFFERENT"

    def covered(x: bytes, y: bytes) -> bool:
        grams = {y[i:i + META_BLOCK] for i in range(len(y) - META_BLOCK + 1)}
        cover = 0  # first byte of x not yet inside a piece found in y
        for i in range(len(x) - META_BLOCK + 1):
            if x[i:i + META_BLOCK] in grams:
                if i > cover:
                    return False
                cover = i + META_BLOCK
        return cover == len(x)

    if covered(sa, sb) and covered(sb, sa):
        return True, (f"same bytes reordered in pieces of {META_BLOCK}+ bytes inside {len(sa)} of {n} bytes "
                      f"(hash map order; run folder names removed)")
    return False, f"DIFFERENT (same byte counts, but reordered below {META_BLOCK}-byte pieces)"


def compare_digests(a: dict, b: dict, meta_a: bytes | None = None, meta_b: bytes | None = None) -> tuple[bool, str]:
    """(guest memory identical and metadata acceptable, a short verdict line). With both stripped
    metadata sections given, compare_meta decides; without them only the hashes remain, and equal
    byte counts are reported as such, not as a reorder."""
    diff = [n for n in SECTIONS[1:] if a["sections"][n] != b["sections"][n]]
    if a["sections"]["meta"] == b["sections"]["meta"]:
        meta_ok, meta = True, "identical"
    elif meta_a is not None and meta_b is not None:
        meta_ok, meta = compare_meta(meta_a, meta_b)
    elif a.get("meta_stripped") is not None and a.get("meta_stripped") == b.get("meta_stripped"):
        meta_ok, meta = True, "identical after removing run folder names"
    elif a["meta_multiset"] == b["meta_multiset"]:
        meta_ok, meta = True, "same byte counts (order not checked: no metadata kept)"
    else:
        meta_ok, meta = False, "DIFFERENT"
    if diff:
        return False, f"guest memory DIFFERS ({', '.join(diff)}); metadata {meta}"
    return meta_ok, f"guest memory identical (FCRAM, VRAM, DSP RAM, AXI WRAM); metadata {meta}"


def meta_path(name: str) -> str:
    return os.path.join(RUNS, name, "meta.bin.z")


def load_meta(name: str) -> bytes | None:
    """The stripped metadata a run kept with keep_meta=True (h4a deletes it after comparing)."""
    try:
        with open(meta_path(name), "rb") as fh:
            return zlib.decompress(fh.read())
    except (OSError, zlib.error):
        return None


