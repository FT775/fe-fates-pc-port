"""Headless game runs for the tier-4 harness (docs/HARNESS.md 4.1, milestone H4a). Standard library only.

Runs the existing windowless Zakuro runner (engine/target/zakuro-test/release/examples/boot.exe) on
the capture library, from a scratch copy of a PLAY save backup, with a scripted button route
(config/harness/routes.json, our own timings). Never opens a window: boot.exe has none, and it is
started with CREATE_NO_WINDOW. Everything it writes goes below build/harness/:

    data/<run>/user/...   scratch save folder (ZAKURO_DATA), a copy of play/backups/<zip>
    tmp/<run>/            TMP/TEMP and working folder: boot.exe's PPM dumps and the savestate
    runs/<run>/           boot.log, run.json (hashes, settings), FE_CAPTURE_DIR in capture mode
                          (summary.tsv, callbacks.tsv, bad records only); meta.bin.z (the
                          stripped state metadata) only while h4a compares, then deleted
    shots/<run>/          one PNG contact sheet of the checkpoint screens

Never touched: %APPDATA%\\zakuro (the real saves), %APPDATA%\\3dsrecomp, the ROM (read only).

The savestate (ZAKURO_SAVE_AT) is hashed and then deleted (states are regenerated by running the
route again, storage policy): its guest memory sections (FCRAM, VRAM, DSP RAM, AXI WRAM) must be
byte-identical between runs; its metadata section (postcard: CPU, kernel, services, GPU) is compared
too, after removing the run's own folder names: Zakuro writes a hash map there in a per-process
order (seen in H4a: the same entries of 4 and 2 bytes in another order), so compare_meta accepts bytes that
are only reordered in pieces of 2+ bytes (h4a keeps the stripped metadata until it has compared).

Used by harness.py (`headless`, `h4a`); `python tools/harness/headless.py --selftest` checks the
parts that need no game (LZ4 decoder, state parsing and comparison, folder and route rules, save packing).
`python tools/harness/headless.py --pack RUN NAME` packs the in-game save a run left in data/RUN/ into
build/harness/saves/NAME.zip (PLAY backup layout); `--save NAME` then starts any route from it.
"""
