    say(f"[{name}] {mode}{'/' + live if mode == 'capture' else ''}: exit {rc}, {result['outcome']} after "
        f"{result['frames']} frames in {secs} s, instructions {result['instructions']}, state "
        f"{'memory ' + result['state']['memory'][:16] if 'state' in result else 'MISSING'}")
    return result


