OPTIONS_ENVS = ("FE_OPTIONS", GAME.env("OPTIONS"))
DROP_PREFIXES = ("ZAKURO_", "FE_", "RUST_LOG")


def child_env(base: dict | None = None) -> dict:
    """A child's environment: base (os.environ) without any inherited ZAKURO_ / FE_ / RUST_LOG setting and without
    the options file's path. Windows names are case-insensitive, so the test is on the upper-case name."""
    base = os.environ if base is None else base
    return {k: v for k, v in base.items()
            if not k.upper().startswith(DROP_PREFIXES) and k.upper() not in OPTIONS_ENVS}


def options_leak(env: dict) -> list[str]:
    """The options-file variables still in env (the self-tests' check; empty is right)."""
    return sorted(k for k in env if k.upper() in OPTIONS_ENVS)


