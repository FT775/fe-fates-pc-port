def refuse_cias(rom: str) -> list[str]:
    """Stops when a .cia lies beside the ROM (Zakuro's frontend loads an update or DLC from the ROM's folder;
    an update changes the code the library was recompiled from). Same reader and rule as PLAY
    (tools/play/play.py classify_cias): this game's DLC is a note, everything else a stop. Returns the notes."""
    sys.path.insert(0, os.path.join(ROOT, "tools", "play"))
    try:
        import play  # noqa: E402  (classify_cias, cia_title_id)
    finally:
        sys.path.pop(0)
    from pathlib import Path
    stops, notes = play.classify_cias(Path(rom))
    if stops:
        raise Stop(f"refused: .cia beside the ROM ({', '.join(stops)}): an update changes the code; move it away")
    return notes


def find_backup(arg: str | None) -> str:
    """A save zip to start from: a path below play/backups/ or build/harness/, or the bare name of a zip in
    build/harness/saves/ (pack_save), or None for the newest PLAY backup."""
    if arg and not os.path.exists(arg) and re.fullmatch(r"[A-Za-z0-9_.-]+", arg):
        named = os.path.join(SAVES, arg if arg.endswith(".zip") else arg + ".zip")
        if os.path.isfile(named):
            arg = named
    if arg:
        path = os.path.abspath(arg)
        if not (below(path, BACKUPS) or below(path, BUILD)) or not os.path.isfile(path):
            raise Stop(f"--save {arg}: must be a zip below play/backups/ or build/harness/")
        return path
    # a Seal edition save (play.py --backup-seal: manual-<time>-seal.zip, round 73b) is never a Fates start save
    zips = sorted((z for z in glob.glob(os.path.join(BACKUPS, "*.zip")) if not z.endswith("-seal.zip")),
                  key=os.path.getmtime)
    if not zips:
        raise Stop("no save backup in play/backups/ (PLAY makes one before each start)")
    return zips[-1]


# the game's SD extra data (Zakuro's user/extdata/<16 hex>/): the map's battle save lives there (round 6: Map0.bak
# after system menu > Save on a map), so a pack with extdata=True keeps it; every other pack holds savedata only
EXTDATA_RX = r"extdata/[0-9A-Fa-f]{16}(\.format$|/)"


def save_fingerprint(zip_path: str) -> str:
    """sha256 over the save members of a zip (name and bytes, sorted; the cheat mark left out): two zips with the
    same save files have the same fingerprint, whatever they are called."""
    h = hashlib.sha256()
    with zipfile.ZipFile(zip_path) as z:
        for n in sorted(i.filename for i in z.infolist() if not i.is_dir() and i.filename not in MARKS):
            data = z.read(n)
            h.update(n.encode() + b"\0" + str(len(data)).encode() + b"\0" + data)
    return h.hexdigest()


def save_is_cheat(zip_path: str) -> str | None:
    """Why a start save carries cheat state (docs/CHEATS.md rule 3), or None for a real-play save. Three tests, so
    neither a new name nor a copy launders it: the file is named cheat-*; the zip holds the cheat mark (pack_save
    writes it into every save of a cheat run); or its save files are byte for byte those of a cheat save in
    build/harness/saves/ (a cheat zip copied, or repacked without the mark)."""
    if os.path.basename(zip_path).startswith("cheat-"):
        return "named cheat-*"
    with zipfile.ZipFile(zip_path) as z:
        if CHEAT_MARK in z.namelist():
            return f"carries the cheat mark ({CHEAT_MARK})"
    fp = save_fingerprint(zip_path)
    for folder in dict.fromkeys((SAVES, _REPO_SAVES)):
        for other in sorted(glob.glob(os.path.join(folder, "*.zip"))):
            if os.path.abspath(other) == os.path.abspath(zip_path):
                continue
            try:
                with zipfile.ZipFile(other) as z:
                    marked = CHEAT_MARK in z.namelist()
                if (marked or os.path.basename(other).startswith("cheat-")) and save_fingerprint(other) == fp:
                    return f"same save files as the cheat save {rel(other)}"
            except (OSError, zipfile.BadZipFile):
                continue
    return None


def check_start_save(route_name: str, route: dict, zip_path: str) -> str | None:
    """docs/CHEATS.md rule 3 at run time: a cheat save never starts a real-play route, whether the route names it
    or --save does. Returns why the save is a cheat save (recorded as run.json start_save_cheat), or None."""
    why = save_is_cheat(zip_path)
    if why and not _cheats().is_cheat(route):
        raise Stop(f"route {route_name} is real play, but its start save {rel(zip_path)} is a cheat save ({why}): "
                   f"cheat state never starts a real-play run (use a cheat-* route)")
    why_opt = save_is_options(zip_path)  # options_track.py rule 3: only an options route starts from an options save
    if why_opt and not _options_track().is_options(route):
        raise Stop(f"route {route_name} has no \"options\", but its start save {rel(zip_path)} is an options save "
                   f"({why_opt}): options-track state never starts a real-play or cheat run")
    return why


def lay_save(zip_path: str, data_dir: str) -> list[str]:
    """Extracts a PLAY backup (paths relative to Zakuro's user folder) into data_dir/user. The cheat mark of a
    cheat save is checked by save_is_cheat and not laid out (the game never sees it)."""
    user = os.path.join(data_dir, "user")
    names = []
    with zipfile.ZipFile(zip_path) as z:
        members = [i for i in z.infolist() if i.filename not in MARKS]
        for info in members:
            target = os.path.abspath(os.path.join(user, info.filename))
            ok = info.filename.startswith("savedata/" + TITLE) or re.match(EXTDATA_RX, info.filename)
            if not below(target, user) or not ok:
                raise Stop(f"{rel(zip_path)}: unexpected member {info.filename}")
            names.append(info.filename)
        z.extractall(user, members=members)
    return names


def pack_save(data_dir: str, name: str, max_bytes: int = 1 << 20, extdata: bool = False) -> dict:
    """Packs the save files a run left in its scratch folder (data_dir/user/savedata/<title>*) into
    build/harness/saves/<name>.zip, in the PLAY backup layout (paths relative to the user folder), so that
    lay_save and every route can start from it (--save <name>). Save files only: no state, no ROM data."""
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", name):
        raise Stop(f"save name {name}: letters, digits, _ . - only")
    data_dir = os.path.abspath(data_dir)
    if not below(data_dir, os.path.join(BUILD, "data")):
        raise Stop(f"{data_dir}: not a run folder below build/harness/data/")
    run_json = os.path.join(RUNS, os.path.basename(data_dir), "run.json")
    if not os.path.isfile(run_json):
        raise Stop(f"{rel(data_dir)}: its run has not finished (no runs/{os.path.basename(data_dir)}/run.json)")
    with open(run_json, encoding="utf-8") as fh:
        rj = json.load(fh)
    outcome = rj.get("outcome")
    # docs/CHEATS.md rule 3: a run is a cheat run when its route pokes OR its start save carries cheat state
    # (run() records start_save_cheat; a run.json without it is checked against its start save zip now)
    cheat = bool(rj.get("cheat")) or bool(rj.get("start_save_cheat"))
    if not cheat and "start_save_cheat" not in rj and rj.get("save_backup"):
        start = rj["save_backup"] if os.path.isabs(rj["save_backup"]) else os.path.join(ROOT, rj["save_backup"])
        if not os.path.isfile(start):
            raise Stop(f"{rel(run_json)}: its start save {rj['save_backup']} is gone, so it cannot be told whether "
                       f"the run carries cheat state; run it again")
        cheat = save_is_cheat(start) is not None
    if cheat != name.startswith("cheat-"):  # a cheat save is named cheat-*, and only a cheat save
        raise Stop(f"save name {name}: a save packed from a cheat run is named cheat-*, and only such a save "
                   f"(this run is {'a cheat run' if cheat else 'real play'})")
    # options_track.py rule 2: a save of an options run (its route had "options", or it started from an options save)
    # carries the options mark and is named opts-*, and only such a save is
    opts = bool(rj.get("options_run")) or bool(rj.get("start_save_options"))
    if not opts and "start_save_options" not in rj and rj.get("save_backup"):
        start = rj["save_backup"] if os.path.isabs(rj["save_backup"]) else os.path.join(ROOT, rj["save_backup"])
        # a run.json from before this rule: its start save decides (no options save existed then, so a start save
        # that is gone since is judged by its name only)
        opts = (save_is_options(start) is not None if os.path.isfile(start)
                else os.path.basename(start).startswith(_options_track().SAVE_PREFIX))
    if opts != name.startswith(_options_track().SAVE_PREFIX):
        raise Stop(f"save name {name}: a save packed from an options-track run is named "
                   f"{_options_track().SAVE_PREFIX}*, and only such a save "
                   f"(this run is {'an options-track run' if opts else 'not one'})")
    if outcome != "Completed":
        raise Stop(f"{rel(run_json)}: outcome {outcome}, not Completed")
    user = os.path.join(data_dir, "user")
    files = []
    for path in sorted(glob.glob(os.path.join(user, "savedata", TITLE + "*"))):
        for root, _dirs, names in os.walk(path) if os.path.isdir(path) else [(os.path.dirname(path), [], [os.path.basename(path)])]:
            for n in sorted(names):
                files.append(os.path.join(root, n))
    if not files:
        raise Stop(f"{rel(user)}: no save files of {TITLE}")
    if extdata:  # the battle save (a map save) is in the game's extra data, not in savedata
        for root, _dirs, names in os.walk(os.path.join(user, "extdata")):
            for n in sorted(names):
                f = os.path.join(root, n)
                if re.match(EXTDATA_RX, os.path.relpath(f, user).replace("\\", "/")):
                    files.append(f)
    # a run name used again: the old run.json is there while the new run still writes its saves
    if max(os.path.getmtime(f) for f in files) > os.path.getmtime(run_json):
        raise Stop(f"{rel(run_json)} is older than the save files: the run has not finished")
    os.makedirs(SAVES, exist_ok=True)
    out = os.path.join(SAVES, name + ".zip")
    tmp = out + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(f, os.path.relpath(f, user).replace("\\", "/"))
        if cheat:  # the mark travels with the save: save_is_cheat finds it under any name
            z.writestr(CHEAT_MARK, json.dumps({"cheat": True, "run": os.path.basename(data_dir),
                                               "route": rj.get("route"), "start_save": rj.get("save_backup"),
                                               "pokes": len(rj.get("pokes") or [])}, indent=1))
        if opts:  # the options mark travels with the save too (options_track.py rule 2)
            z.writestr(OPTIONS_MARK, _options_track().mark_text(rj, os.path.basename(data_dir)))
    size = os.path.getsize(tmp)
    if size > max_bytes:
        os.remove(tmp)
        raise Stop(f"{name}.zip would be {size} bytes (cap {max_bytes}): not a save folder")
    os.replace(tmp, out)
    with zipfile.ZipFile(out) as z:
        members = {i.filename: i.file_size for i in z.infolist()}
    return {"zip": rel(out), "bytes": size, "sha256": sha256_file(out), "members": members}


