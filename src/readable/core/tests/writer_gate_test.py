#!/usr/bin/env python3
"""Host test of the writer gate and the writer undo log (src/readable/core/writer.c,
src/readable/core/fe_writer.h; docs/WRITERS.md).

    python src/readable/core/tests/writer_gate_test.py           the checks + a random store/undo run
    python src/readable/core/tests/writer_gate_test.py --plant   also plant bugs: each must be caught

A fake guest machine (four writable RAM pages, a read-only page, a device address with no page
pointer) and small C "guest functions" that store the way generated code does (the direct page
when write_pages has one, else the host callback). Every value is invented; no game data.

What it proves:
  - a writer that is OFF (not armed, not listed in FE_WRITERS, or a mode other than readable)
    makes ZERO stores and logs nothing; shadow / capture / original are counted as mode refusals;
    a session opened in readable mode refuses every store once the mode is shadow;
  - every store (1, 2, 4 bytes, overlapping ones too, and every store of a guest function run
    with fe_writer_call, also one nested inside another) is logged with address, size, old and
    new value, writer id, frame and session, and fe_writer_end(keep = 0) / fe_writer_undo_last
    put back every byte exactly; a random run of 3000 sessions compares the memory with a model;
  - stores that cannot be undone (no page pointer, a bad size), an svc or an interpreter escape
    inside fe_writer_call, a full log: refused, the session rolls back whole;
  - undo is exact or nothing: a byte changed since the session gives FE_WRITER_CONFLICT and
    changes nothing;
  - bounded memory: kept sessions are dropped whole, oldest first, when the log is full; an open
    session never is (it fails instead);
  - one session at a time; stores with no session are refused and counted;
  - the source: every writer's `armed` value in writer.c is 0, and the gate reads no file and no
    environment variable other than FE_WRITERS (a green report cannot switch anything on).

Built with the host C compiler (FE_HOST_CC, or tools/readable/check.py's search) against the
stand-in tools/readable/stub/overrides.h, linked with src/readable/core/{writer,runtime}.c, with
-DFE_WRITER_TESTS. SKIPs (exit 0, says so) without a compiler. Writes only under
build/readable/writers/gate/.
"""
