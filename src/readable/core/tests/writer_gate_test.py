def plant(cc: str) -> int:
    missed = 0
    for i, (old, new) in enumerate(PLANTS, 1):
        d = os.path.join(OUT, "plant", "core")
        shutil.rmtree(d, ignore_errors=True)
        shutil.copytree(SRC_CORE, d, ignore=shutil.ignore_patterns("tests"))
        path = os.path.join(d, "writer.c")
        body = open(path, encoding="utf-8").read()
        if body.count(old) != 1:
            print(f"  planted bug {i}: its text occurs {body.count(old)} times (the list is stale)")
            missed += 1
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body.replace(old, new))
        rc, out = build_and_run(cc, d, os.path.join(OUT, "plant", f"p{i:02d}"))  # one exe per bug
        errs = source_checks(d)
        if rc == 2 and not errs:  # it did not build: the plant is wrong, a warning is not a catch
            print(f"  planted bug {i:2d}: does not build (fix the plant): {out.strip().splitlines()[-1][:120]}")
            missed += 1
            continue
        caught = rc != 0 or bool(errs)
        how = (f"source check: {errs[0]}" if errs else
               next((ln.strip() for ln in out.splitlines() if "FAIL" in ln), out.strip().splitlines()[-1] if out.strip() else f"exit {rc}"))
        print(f"  planted bug {i:2d} ({old.strip()[:50]!r}): " + (f"caught ({how[:90]})" if caught else "NOT CAUGHT"))
        missed += 0 if caught else 1
    return missed


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--plant", action="store_true", help="also check that planted bugs are caught")
    a = ap.parse_args(argv)
    errs = source_checks()
    for e in errs:
        print(f"  {e}")
    cc = find_cc()
    if not cc:
        print("writer_gate_test: SKIPPED the C part (no host C compiler; set FE_HOST_CC)")
        return 1 if errs else 0
    rc, out = build_and_run(cc, SRC_CORE, OUT)
    print(out.rstrip())
    missed = 0
    if a.plant:
        missed = plant(cc)
        print(f"writer_gate_test: planted bugs: {len(PLANTS) - missed}/{len(PLANTS)} caught")
    ok = rc == 0 and not errs and not missed
    print(f"writer_gate_test: {'OK' if ok else 'FAILED'} (source checks {'clean' if not errs else len(errs)}"
          + (f", {len(PLANTS) - missed}/{len(PLANTS)} planted bugs caught" if a.plant else "") + ")")
    return 0 if ok else 1


