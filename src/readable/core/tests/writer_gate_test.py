def find_cc() -> str | None:
    import check  # tools/readable/check.py: the same compiler search
    return check.find_cc()


def build_and_run(cc: str, core_dir: str, out: str) -> tuple[int, str]:
    os.makedirs(out, exist_ok=True)
    src = os.path.join(out, "writer_gate_test.c")
    with open(src, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEST)
    exe = os.path.join(out, "writer_gate_test.exe" if os.name == "nt" else "writer_gate_test")
    inc = ["-I", core_dir, "-I", os.path.join(ROOT, "tools", "readable", "stub"),
           "-I", os.path.join(ROOT, "include", "readable"), "-I", os.path.join(ROOT, "include", "readable", "generated")]
    cmd = [cc, "-std=c11", "-Wall", "-Wextra", "-Wpedantic", "-Werror", "-O1", "-fwrapv", "-DFE_WRITER_TESTS"] + inc \
        + [src, os.path.join(core_dir, "writer.c"), os.path.join(core_dir, "runtime.c"), "-o", exe]
    env = dict(os.environ)
    env["PATH"] = os.path.dirname(cc) + os.pathsep + env.get("PATH", "")
    r = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if r.returncode:
        return 2, f"build failed:\n{r.stdout}{r.stderr}"
    env["FE_READABLE_LOG"] = os.path.join(out, "fe_readable.log")
    env.pop("FE_WRITERS", None)
    try:
        r = subprocess.run([exe], capture_output=True, text=True, env=env, timeout=60)
    except subprocess.TimeoutExpired:
        return 3, "timed out"
    return r.returncode, r.stdout + r.stderr


def source_checks(core_dir: str = SRC_CORE) -> list[str]:
    """Nothing switched on, and nothing but FE_WRITERS can switch a writer on."""
    errs = []
    text = open(os.path.join(core_dir, "writer.c"), encoding="utf-8").read()
    m = re.search(r"fe_writer_table\[FE_WRITER_COUNT\]\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        errs.append("writer.c: the writer table was not found")
    else:
        rows = re.findall(r'\{\s*"([^"]*)"\s*,\s*([^}\s]+)\s*\}', m.group(1))
        if len(rows) < 2:
            errs.append("writer.c: the writer table has no writer")
        for name, armed in rows:
            if armed != "0":
                errs.append(f"writer.c: writer {name!r} is armed ({armed}); every writer ships OFF")
    for bad in ("fopen", "fread", "getenv(\"FE_READABLE\"", ".csv", "targets", "verified"):
        if bad in re.sub(r"/\*.*?\*/", "", text, flags=re.S):
            errs.append(f"writer.c: reads {bad!r}: only FE_WRITERS and the mode may switch a writer")
    envs = re.findall(r'getenv\("([^"]+)"\)', text)
    if envs != ["FE_WRITERS"]:
        errs.append(f"writer.c: environment variables read: {envs} (only FE_WRITERS)")
    if not re.search(r"#ifndef FE_WRITER_TESTS|#ifdef FE_WRITER_TESTS", text):
        errs.append("writer.c: the test hooks are not behind FE_WRITER_TESTS")
    return errs


